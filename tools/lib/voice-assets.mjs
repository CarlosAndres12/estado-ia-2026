/* tools/lib/voice-assets.mjs — the files the voice-over leaves for the site (prompt §8.3 step 8).
 *
 * Dev-only (Node >= 20, built-ins only).
 *
 *   toVtt(entry, video)        WebVTT text for assets/captions/<id>.vtt: one cue per subtitle chunk,
 *                              with a <v Narrador> / <v Lectora> voice span (text exactly as displayed)
 *   manifestSource(manifest)   the classic script assets/audio/manifest.js (window.EIA.audioManifest),
 *                              one manifest line per voice line so diffs stay readable
 *   readManifest(file)         the manifest an earlier run wrote ({} when there is none)
 *   formatTime(seconds)        'm:ss.s' for reports and listening sheets
 *   vttTime(seconds)           'hh:mm:ss.mmm'
 */

import fs from 'node:fs';
import vm from 'node:vm';

export function vttTime(seconds) {
  const ms = Math.max(0, Math.round(seconds * 1000));
  const h = Math.floor(ms / 3600000);
  const m = Math.floor((ms % 3600000) / 60000);
  const s = Math.floor((ms % 60000) / 1000);
  const pad = (n, w = 2) => String(n).padStart(w, '0');
  return `${pad(h)}:${pad(m)}:${pad(s)}.${pad(ms % 1000, 3)}`;
}

export function formatTime(seconds) {
  const tenths = Math.max(0, Math.round(seconds * 10));
  const m = Math.floor(tenths / 600);
  const s = (tenths % 600) / 10;
  return `${m}:${s < 10 ? '0' : ''}${s.toFixed(1)}`;
}

const escapeCue = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** WebVTT for one video: every chunk of every line, in time order. */
export function toVtt(entry, video) {
  const voiceOf = {};
  for (const scene of video.scenes) (scene.lines || []).forEach((line, i) => { voiceOf[scene.id + ':' + i] = line.voice; });
  const cues = [];
  for (const line of entry.lines) {
    const speaker = voiceOf[line.scene + ':' + line.index] === 'lectora' ? 'Lectora' : 'Narrador';
    for (const chunk of line.chunks) {
      const end = Math.max(chunk.end, chunk.start + 0.1);
      cues.push(`${cues.length + 1}\n${vttTime(chunk.start)} --> ${vttTime(end)}\n<v ${speaker}>${escapeCue(chunk.text)}`);
    }
  }
  const title = String(video.title || video.id).replace(/-->/g, '→');
  return `WEBVTT\n\nNOTE ${video.id} · ${title} — generated by tools/generate-voiceover.mjs\n\n${cues.join('\n\n')}\n`;
}

/** assets/audio/manifest.js (contracts §2), entries in the given order. */
export function manifestSource(manifest) {
  const json = (value) => JSON.stringify(value);
  const videos = Object.entries(manifest).map(([id, e]) => [
    `  ${json(id)}: {`,
    `    "file": ${json(e.file)}, "duration": ${json(e.duration)},`,
    `    "chapters": ${json(e.chapters)},`,
    `    "scenes": [\n${e.scenes.map((s) => '      ' + json(s)).join(',\n')}\n    ],`,
    `    "lines": [\n${e.lines.map((l) => '      ' + json(l)).join(',\n')}\n    ],`,
    `    "checkpoints": ${json(e.checkpoints)}`,
    '  }'
  ].join('\n'));
  return '/* GENERATED by tools/generate-voiceover.mjs — do not edit by hand.\n' +
    ' * { [videoId]: { file, duration, chapters, scenes, lines: [{ scene, index, start, dur, chunks: [{ text, start, end }] }], checkpoints } }\n' +
    ' * Times are seconds from the start of the video. Empty until the narration is generated: the player\n' +
    ' * then uses the browser voice. */\n' +
    'window.EIA = window.EIA || {};\n' +
    `window.EIA.audioManifest = {${videos.length ? '\n' + videos.join(',\n') + '\n' : ''}};\n`;
}

/** The manifest written by an earlier run, as plain data ({} when the file does not exist). */
export function readManifest(file) {
  let code;
  try {
    code = fs.readFileSync(file, 'utf8');
  } catch {
    return {};
  }
  const sandbox = {};
  sandbox.window = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { filename: file });
  const manifest = sandbox.EIA && sandbox.EIA.audioManifest;
  return manifest ? JSON.parse(JSON.stringify(manifest)) : {};
}
